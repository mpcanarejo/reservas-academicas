
CREATE TABLE usuario (
    id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR2(100) NOT NULL,
    correo    VARCHAR2(100) NOT NULL UNIQUE,
    rol       VARCHAR2(30)
);


CREATE TABLE espacio (
    id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR2(100) NOT NULL,
    tipo      VARCHAR2(50),
    capacidad NUMBER(5)
);

CREATE TABLE horario (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espacio_id   NUMBER NOT NULL,
    dia_semana   VARCHAR2(20) NOT NULL,
    hora_inicio  TIMESTAMP NOT NULL,
    hora_fin     TIMESTAMP NOT NULL,
    CONSTRAINT fk_horario_espacio FOREIGN KEY (espacio_id) REFERENCES espacio (id)
);


CREATE TABLE reserva (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   NUMBER NOT NULL,
    espacio_id   NUMBER NOT NULL,
    fecha        DATE NOT NULL,
    hora_inicio  TIMESTAMP NOT NULL,
    hora_fin     TIMESTAMP NOT NULL,
    estado       VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    motivo       VARCHAR2(200),
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_reserva_espacio FOREIGN KEY (espacio_id) REFERENCES espacio (id)
);


CREATE INDEX idx_horario_espacio ON horario (espacio_id);
CREATE INDEX idx_reserva_usuario ON reserva (usuario_id);
CREATE INDEX idx_reserva_espacio ON reserva (espacio_id);
CREATE INDEX idx_reserva_fecha   ON reserva (fecha);
